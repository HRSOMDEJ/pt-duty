function helpBox(page) {
  var t = HELP[page];
  if (!t) return '';
  var hidden = false;
  try { hidden = localStorage.getItem('pt_help_' + page) === '0'; } catch (e) {}
  return '<div class="help" id="hb_' + page + '"' + (hidden ? ' hidden' : '') + '>' +
    '<i class="bi bi-info-circle"></i> ' + t +
    ' <a href="#" onclick="hideHelp(\'' + page + '\');return false" style="white-space:nowrap">ซ่อน</a></div>' +
    (hidden ? '<div style="margin-bottom:.6rem"><a href="#" onclick="showHelp(\'' + page + '\');return false" class="sub"><i class="bi bi-info-circle"></i> แสดงวิธีใช้หน้านี้</a></div>' : '');
}
function hideHelp(page) {
  var el = document.getElementById('hb_' + page);
  if (el) el.hidden = true;
  try { localStorage.setItem('pt_help_' + page, '0'); } catch (e) {}
}
function showHelp(page) {
  var el = document.getElementById('hb_' + page);
  if (el) el.hidden = false;
  try { localStorage.removeItem('pt_help_' + page); } catch (e) {}
}
